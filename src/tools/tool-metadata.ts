export function resolveToolAnnotations(
  name: string,
  overrides: ToolAnnotations | undefined,
): ToolAnnotations {
  if (!Object.prototype.hasOwnProperty.call(TOOL_RISK, name)) {
    throw new Error(`Missing explicit risk metadata for MCP tool "${name}"`);
  }

  const risk = TOOL_RISK[name as ToolName];
  return {
    readOnlyHint: risk === "read-only",
    destructiveHint: risk === "destructive",
    idempotentHint: risk === "read-only",
    openWorldHint: !LOCAL_ONLY_TOOL_NAMES.has(name),
    ...overrides,
  };
}
